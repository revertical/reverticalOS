#!/usr/bin/env python3
"""Embed boot binaries and module files in the kernel.

The installer must be able to write a complete boot chain and a set of
working RVLB/RVEX modules even when the running system booted from a CD and
has no boot disk to copy from. The arrays below are the disk-build binaries
(512-byte MBR and 8 KiB stage 2), not the El Torito variants used in the ISO,
plus every --file NAME=PATH passed on the command line.
"""
import argparse
import re
from pathlib import Path

STAGE1_SIZE = 512
STAGE2_SIZE = 16 * 512


def c_array(name: str, data: bytes) -> str:
    out = [f"const unsigned char {name}[{len(data)}] = {{"]
    for i in range(0, len(data), 12):
        chunk = data[i:i + 12]
        out.append("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
    out.append("};")
    out.append(f"const unsigned int {name}_len = {len(data)}u;")
    return "\n".join(out)


def ident(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--stage1", default="build/stage1.bin")
    ap.add_argument("--stage2", default="build/stage2.bin")
    ap.add_argument("--loader", default="build/bootx64.efi",
                    help="UEFI loader embedded for the installer's ESP")
    ap.add_argument("--file", action="append", default=[],
                    help="NAME=PATH module to embed at /System/<kind>/NAME")
    ap.add_argument("--output", default="build/bootblob.c")
    ap.add_argument("--header", default="build/bootblob.h")
    args = ap.parse_args()

    stage1 = Path(args.stage1).read_bytes()
    stage2 = Path(args.stage2).read_bytes()
    loader = Path(args.loader).read_bytes() if args.loader else b""
    if len(stage1) != STAGE1_SIZE:
        raise SystemExit(f"stage1 must be {STAGE1_SIZE} bytes (got {len(stage1)})")
    if len(stage2) != STAGE2_SIZE:
        raise SystemExit(f"stage2 must be {STAGE2_SIZE} bytes (got {len(stage2)})")

    parts = [
        "/* Generated by tools/genblob.py - do not edit. */\n"
        "/* Disk boot chain and module files embedded for the installer. */\n\n"
        '#include "bootblob.h"\n\n',
        c_array("rv_boot_stage1", stage1),
        "\n\n",
        c_array("rv_boot_stage2", stage2),
        "\n\n",
    ]
    if loader:
        parts.append(c_array("rv_bootx64_efi", loader))
        parts.append("\n\n")

    entries = []
    for spec in args.file:
        if "=" not in spec:
            raise SystemExit(f"bad --file {spec!r}, expected NAME=PATH")
        name, path = spec.split("=", 1)
        data = Path(path).read_bytes()
        if name.endswith(".lib"):
            dest = "/System/Libs/" + name
        else:
            dest = "/System/Apps/" + name
        sym = "rv_file_" + ident(name)
        parts.append(c_array(sym, data))
        parts.append("\n\n")
        entries.append((dest, sym, len(data)))

    parts.append("const RvEmbeddedFile rv_embedded_files[] = {\n")
    for dest, sym, size in entries:
        parts.append(f'    {{ "{dest}", {sym}, {size}u }},\n')
    if not entries:
        parts.append("    { 0, 0, 0 },\n")
    parts.append("};\n")
    parts.append(f"const unsigned int rv_embedded_file_count = {len(entries)}u;\n")

    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("".join(parts))

    hdr = Path(args.header)
    hdr.write_text(
        "/* Generated by tools/genblob.py - do not edit. */\n"
        "#ifndef RVOS_BOOTBLOB_H\n"
        "#define RVOS_BOOTBLOB_H\n\n"
        "#include \"types.h\"\n\n"
        "typedef struct {\n"
        "    const char *path;\n"
        "    const unsigned char *data;\n"
        "    unsigned int len;\n"
        "} RvEmbeddedFile;\n\n"
        "extern const RvEmbeddedFile rv_embedded_files[];\n"
        "extern const unsigned int rv_embedded_file_count;\n\n"
        "extern const unsigned char rv_boot_stage1[];\n"
        "extern const unsigned int rv_boot_stage1_len;\n"
        "extern const unsigned char rv_boot_stage2[];\n"
        "extern const unsigned int rv_boot_stage2_len;\n"
        "extern const unsigned char rv_bootx64_efi[];\n"
        "extern const unsigned int rv_bootx64_efi_len;\n\n"
        "#endif\n"
    )

    print(f"bootblob: {out} (stage1 {len(stage1)}, stage2 {len(stage2)}, "
          f"loader {len(loader)}, {len(entries)} module files)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
